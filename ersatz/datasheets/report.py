"""Render an extraction evaluation as Markdown for docs/EXTRACTION_EVAL.md."""

from collections import Counter
from datetime import datetime

from pydantic import BaseModel

from ersatz.datasheets.scoring import LabelScore, Outcome, TypeSummary, summarize
from ersatz.notice import NOTICE


class DatasheetRun(BaseModel, frozen=True):
    id: str
    manufacturer: str
    category: str
    pages_sent: tuple[int, ...] = ()
    kept: int = 0
    dropped: int = 0
    low_confidence: int = 0
    cost_usd: float = 0.0
    input_tokens: int = 0
    output_tokens: int = 0
    cached: bool = False
    error: str | None = None
    drop_reasons: tuple[str, ...] = ()


class EvalRun(BaseModel, frozen=True):
    started_at: datetime
    model: str
    extractor: str
    label_status: str
    datasheets: tuple[DatasheetRun, ...]
    scores: tuple[LabelScore, ...]


def _pct(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.0f}%"


def _rollup(summaries: list[TypeSummary], prefix: str) -> TypeSummary:
    chosen = [s for s in summaries if s.field_type.split(":")[0] == prefix]
    return TypeSummary(
        field_type=prefix,
        labels=sum(s.labels for s in chosen),
        correct=sum(s.correct for s in chosen),
        wrong=sum(s.wrong for s in chosen),
        missing=sum(s.missing for s in chosen),
        cited=sum(s.cited for s in chosen),
    )


def _row(s: TypeSummary) -> str:
    return (
        f"| {s.field_type} | {s.labels} | {s.correct} | {s.wrong} | {s.missing} "
        f"| {_pct(s.field_accuracy)} | {_pct(s.citation_accuracy)} |"
    )


_HEAD = (
    "| Field type | Labels | Correct | Wrong | Missing | Field accuracy | Citation accuracy |\n"
    "|---|---|---|---|---|---|---|"
)


def render(run: EvalRun) -> str:
    scores = list(run.scores)
    summaries = summarize(scores)
    kinds = [_rollup(summaries, k) for k in ("parameter", "package", "pin", "feature")]
    total = TypeSummary(
        field_type="all",
        labels=sum(k.labels for k in kinds),
        correct=sum(k.correct for k in kinds),
        wrong=sum(k.wrong for k in kinds),
        missing=sum(k.missing for k in kinds),
        cited=sum(k.cited for k in kinds),
    )
    cost = sum(d.cost_usd for d in run.datasheets)
    tokens_in = sum(d.input_tokens for d in run.datasheets)
    tokens_out = sum(d.output_tokens for d in run.datasheets)
    lines = [
        "# Extraction evaluation",
        "",
        "Generated by scripts/eval_extraction.py. Do not edit by hand.",
        "",
        f"- Run started: {run.started_at.isoformat(timespec='seconds')}",
        f"- Model: {run.model}",
        f"- Extractor version: {run.extractor}",
        f"- Label status: {run.label_status}",
        f"- Datasheets: {len(run.datasheets)}, labels: {total.labels}",
        f"- Cost of model calls in this run: {cost:.4f} USD "
        f"({tokens_in} input tokens, {tokens_out} output tokens)",
        "",
    ]
    if run.label_status != "REVIEWED":
        lines += [
            "Labels are drafts that have not been spot-checked yet. Scores can change "
            "after review.",
            "",
        ]
    lines += ["## Summary by kind", "", _HEAD, *(_row(k) for k in kinds), _row(total), ""]
    lines += ["## Per field type", "", _HEAD, *(_row(s) for s in summaries), ""]
    lines += [
        "## Per datasheet",
        "",
        "| Datasheet | Manufacturer | Category | Pages sent | Kept | Dropped | LOW | "
        "Field accuracy | Cost USD | Note |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for d in run.datasheets:
        mine = [s for s in scores if s.datasheet == d.id]
        acc = sum(s.outcome is Outcome.CORRECT for s in mine) / len(mine) if mine else None
        note = d.error or ("cached reply" if d.cached else "")
        pages = ", ".join(map(str, d.pages_sent)) or "-"
        lines.append(
            f"| {d.id} | {d.manufacturer} | {d.category} | {pages} | {d.kept} | {d.dropped} "
            f"| {d.low_confidence} | {_pct(acc)} | {d.cost_usd:.4f} | {note} |"
        )
    lines.append("")
    failures = [s for s in scores if s.outcome is not Outcome.CORRECT]
    lines += ["## Failures", ""]
    if failures:
        lines += ["| Datasheet | Field | Outcome | Expected | Extracted |", "|---|---|---|---|---|"]
        for s in failures:
            lines.append(
                f"| {s.datasheet} | {s.field_type} {s.label} | {s.outcome.value} "
                f"| {s.expected} | {s.got} |"
            )
    else:
        lines.append("None.")
    lines.append("")
    miscited = [s for s in scores if s.outcome is Outcome.CORRECT and not s.cited_ok]
    lines += ["## Correct values with a citation outside the labeled pages", ""]
    if miscited:
        lines += ["| Datasheet | Field | Expected | Extracted |", "|---|---|---|---|"]
        lines += [
            f"| {s.datasheet} | {s.field_type} {s.label} | {s.expected} | {s.got} |"
            for s in miscited
        ]
    else:
        lines.append("None.")
    lines.append("")
    reasons = Counter(r for d in run.datasheets for r in d.drop_reasons)
    lines += ["## Values dropped by quote verification or validation", ""]
    if reasons:
        lines += ["| Reason | Count |", "|---|---|"]
        lines += [f"| {reason} | {count} |" for reason, count in reasons.most_common()]
    else:
        lines.append("None.")
    lines += ["", f"Notice: {NOTICE}", ""]
    return "\n".join(lines)
